str1 = "My name is Faheem Sajid"
print(len(str1))           #returns length of string
print(str1.upper())        #Convert Uppercase
print(str1.lower())        #Convert Lowercase
print(str1.rstrip("d"))    #Removes trailing character
print(str1.replace("Faheem","Awais"))   #Replace str with another string
print(str1.split())        #Split the str from spaces and returns list
print(str1.capitalize())   #Covert 1st char to uppercase and rest into lowercase
print(str1.center(50))     #aligns the str to the centre
print(str1.count("i"))     #returns the number of occurance of the given vlaue
print(str1.endswith("Sajid"))   #checks whether the strings ends with the given value or not
print(str1.find("d"))      #returns the 1st occurance of the given value if doesnt exist returns the -1
print(str1.index("d"))     #returns the 1st occurance index or returns the error
print(str1.isalnum())      #checks for alpha numeric string
print(str1.isalpha())      #checks the alphabetic string
print(str1.islower())      #checks for lower case strings
print(str1.isupper())      #checks for upper case strings
print(str1.isprintable())  #checks for printable character in string
print(str1.isspace())      #checks for the white space
print(str1.istitle())      #checks if the first char of each word is uppercase
print(str1.startswith("My")) #check if the string starts with given value
print(str1.swapcase())      #Swaps all character into upper and lower cases
print(str1.title())         #Capitalize each first letter of the word in the string









